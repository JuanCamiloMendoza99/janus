"""Render a prompt sweep as the markdown tables in `docs/evals/prompts.md`.

    python scripts/report_prompt_eval.py

Compares the playbook variants on a fixed model: the objective metrics from Phase
4, plus each variant's prefix token count and, when a judge pass is present, the
judge's free-text scores and its calibration against hand scores. Only the block
between the generated markers is rewritten; the champion, and the trade-off it
accepts, are written by a human above it.

Reads the latest `results-prompts-*.json` and, unless told otherwise, the latest
`judge-*.json` beside it. Table rendering lives in `app/evals/report.py`.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from app.domain.prompts import VARIANTS
from app.evals.judge import JudgeRun, load_judge_run
from app.evals.report import (
    BEGIN,
    END,
    agreement_table,
    prompt_comparison_table,
    skeleton,
    splice,
)
from app.evals.results import load_runs
from app.evals.runner import RunResult
from app.evals.scoring import Metrics, score

DEFAULT_DIR = Path("docs/evals")


def _latest(directory: Path, glob: str) -> Path | None:
    candidates = sorted(directory.glob(glob))
    return candidates[-1] if candidates else None


def _generated_block(
    rows: list[tuple[RunResult, Metrics]],
    tokens: dict[str, int],
    judge: JudgeRun | None,
    source: Path,
) -> str:
    run = rows[0][0]
    total = sum(metrics.total_cost_usd for _, metrics in rows)
    slice_name = run.split or "train + holdout"
    lines = [
        BEGIN,
        "",
        f"_Generated by `scripts/report_prompt_eval.py` from `{source.name}`. "
        "Everything below this line is derived; do not hand-edit._",
        "",
        f"- **Model (fixed)**: `{run.config.model}`"
        f"{' + adaptive thinking' if run.config.adaptive_thinking else ''}",
        f"- **Dataset**: {rows[0][1].tickets} tickets ({slice_name})",
        f"- **Run**: {run.started_at:%Y-%m-%d %H:%M} UTC",
        f"- **Triage spend**: ${total:.4f}"
        + (f"  ·  **Judge spend**: ${judge.total_cost_usd:.4f}" if judge else ""),
        "",
        "## Comparison",
        "",
        "Objective metrics are the same ones Phase 4 reports, on the held-out "
        "slice. `Prefix tokens` is the cacheable playbook counted by the vendor's "
        "tokenizer — the cost a better prompt is traded against."
        + (
            " The four rightmost columns are the judge's mean 1–5 scores for the "
            "free-text fields; they inform, they do not overrule the objective metrics."
            if judge
            else ""
        ),
        "",
        prompt_comparison_table(rows, tokens, judge),
    ]
    if judge:
        lines += [
            "## Judge calibration",
            "",
            "Before trusting the judge on the variants, it graded a set of "
            "hand-scored examples spanning strong, vague and deliberately "
            "unfaithful outputs. Exact agreement is strict; mean absolute error "
            "says whether the disagreements are near-misses.",
            "",
            agreement_table(judge),
            "",
        ]
    lines.append(END)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=None)
    parser.add_argument("--judge", type=Path, default=None)
    parser.add_argument("--no-judge", action="store_true", help="Ignore any judge file.")
    parser.add_argument("--out", type=Path, default=DEFAULT_DIR / "prompts.md")
    parser.add_argument("--dir", type=Path, default=DEFAULT_DIR)
    args = parser.parse_args(argv)

    source = args.results or _latest(args.dir, "results-prompts-*.json")
    if source is None:
        raise SystemExit(
            f"No results-prompts-*.json in {args.dir}. Run scripts/run_eval.py --prompts first."
        )

    rows = [(run, score(run.outcomes)) for run in load_runs(source)]
    if not rows:
        raise SystemExit(f"{source} contains no runs.")

    tokens = {name: variant.measured_tokens for name, variant in VARIANTS.items()}

    judge: JudgeRun | None = None
    if not args.no_judge:
        judge_path = args.judge or _latest(args.dir, "judge-*.json")
        if judge_path is not None:
            judge = load_judge_run(judge_path)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    existing = args.out.read_text(encoding="utf-8") if args.out.exists() else skeleton()
    args.out.write_text(
        splice(existing, _generated_block(rows, tokens, judge, source)), encoding="utf-8"
    )

    print(f"{source} -> {args.out}" + (f" (+ {judge_path.name})" if judge else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
